import type { SupabaseClient } from '@supabase/supabase-js';
import { jsPDF } from 'jspdf';

interface InvoiceData {
  invoiceRef: string;
  vesselName: string;
  vesselImo: string;
  vesselMmsi: string;
  ownerName: string;
  jurisdiction: string;
  periodStart: string;
  periodEnd: string;
  emissionsTco2: number;
  ratePerTco2: number;
  subtotalUsd: number;
  exemptionUsd: number;
  totalUsd: number;
  lineItems: Array<{
    zone: string;
    days: number;
    emissionsTco2: number;
    rate: number;
    amount: number;
  }>;
}

/**
 * Generate a carbon tax invoice PDF.
 * Returns the PDF as a Uint8Array buffer.
 */
export function generateInvoicePdf(data: InvoiceData): Uint8Array {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();

  // Header
  doc.setFillColor(10, 17, 16); // #0A1110
  doc.rect(0, 0, pageWidth, 40, 'F');
  doc.setTextColor(16, 185, 129); // emerald
  doc.setFontSize(22);
  doc.text('AfricgreenOS', 15, 18);
  doc.setFontSize(10);
  doc.setTextColor(200, 200, 200);
  doc.text('Sovereign Carbon Intelligence Platform', 15, 26);
  doc.text('Republic of Somaliland — Maritime Carbon Tax Authority', 15, 32);

  // Invoice details
  doc.setTextColor(0, 0, 0);
  doc.setFontSize(16);
  doc.text('CARBON TAX INVOICE', 15, 55);

  doc.setFontSize(10);
  const detailsY = 65;
  const col1 = 15;
  const col2 = 110;

  doc.setFont('helvetica', 'bold');
  doc.text('Invoice Ref:', col1, detailsY);
  doc.text('Date:', col1, detailsY + 6);
  doc.text('Period:', col1, detailsY + 12);
  doc.text('Jurisdiction:', col1, detailsY + 18);

  doc.setFont('helvetica', 'normal');
  doc.text(data.invoiceRef, col1 + 30, detailsY);
  doc.text(new Date().toLocaleDateString('en-GB'), col1 + 30, detailsY + 6);
  doc.text(`${data.periodStart} — ${data.periodEnd}`, col1 + 30, detailsY + 12);
  doc.text(data.jurisdiction, col1 + 30, detailsY + 18);

  doc.setFont('helvetica', 'bold');
  doc.text('Vessel:', col2, detailsY);
  doc.text('IMO:', col2, detailsY + 6);
  doc.text('MMSI:', col2, detailsY + 12);
  doc.text('Owner:', col2, detailsY + 18);

  doc.setFont('helvetica', 'normal');
  doc.text(data.vesselName, col2 + 20, detailsY);
  doc.text(data.vesselImo, col2 + 20, detailsY + 6);
  doc.text(data.vesselMmsi, col2 + 20, detailsY + 12);
  doc.text(data.ownerName, col2 + 20, detailsY + 18);

  // Line items table
  const tableY = detailsY + 30;
  doc.setFillColor(240, 240, 240);
  doc.rect(col1, tableY, pageWidth - 30, 8, 'F');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.text('Zone', col1 + 2, tableY + 5);
  doc.text('Days', col1 + 45, tableY + 5);
  doc.text('Emissions (tCO2)', col1 + 65, tableY + 5);
  doc.text('Rate ($/tCO2)', col1 + 105, tableY + 5);
  doc.text('Amount (USD)', col1 + 140, tableY + 5);

  doc.setFont('helvetica', 'normal');
  let rowY = tableY + 14;
  for (const item of data.lineItems) {
    doc.text(item.zone, col1 + 2, rowY);
    doc.text(String(item.days), col1 + 45, rowY);
    doc.text(item.emissionsTco2.toFixed(2), col1 + 65, rowY);
    doc.text(`$${item.rate.toFixed(2)}`, col1 + 105, rowY);
    doc.text(`$${item.amount.toFixed(2)}`, col1 + 140, rowY);
    rowY += 7;
  }

  // Totals
  rowY += 5;
  doc.setDrawColor(200, 200, 200);
  doc.line(col1, rowY - 3, pageWidth - 15, rowY - 3);

  doc.setFont('helvetica', 'bold');
  doc.text('Subtotal:', col1 + 105, rowY);
  doc.text(`$${data.subtotalUsd.toFixed(2)}`, col1 + 140, rowY);

  if (data.exemptionUsd > 0) {
    rowY += 7;
    doc.setTextColor(16, 185, 129);
    doc.text('Exemption:', col1 + 105, rowY);
    doc.text(`-$${data.exemptionUsd.toFixed(2)}`, col1 + 140, rowY);
    doc.setTextColor(0, 0, 0);
  }

  rowY += 7;
  doc.setFontSize(12);
  doc.text('TOTAL DUE:', col1 + 95, rowY);
  doc.text(`$${data.totalUsd.toFixed(2)}`, col1 + 140, rowY);

  // Footer
  const footerY = 270;
  doc.setFontSize(8);
  doc.setTextColor(128, 128, 128);
  doc.text('Payment: Wire transfer or Wave Mobile Money — Reference: ' + data.invoiceRef, col1, footerY);
  doc.text('Generated by AfricgreenOS — Sovereign Carbon Intelligence Platform', col1, footerY + 5);
  doc.text(`Document generated on ${new Date().toISOString()}`, col1, footerY + 10);

  return doc.output('arraybuffer') as unknown as Uint8Array;
}

/**
 * Generate invoice PDF and upload to Supabase Storage.
 * Returns the public URL of the uploaded PDF.
 */
export async function generateAndStoreInvoice(
  client: SupabaseClient,
  data: InvoiceData,
): Promise<string | null> {
  const pdfBuffer = generateInvoicePdf(data);
  const fileName = `invoices/${data.invoiceRef}.pdf`;

  const { error: uploadError } = await client.storage
    .from('documents')
    .upload(fileName, pdfBuffer, {
      contentType: 'application/pdf',
      upsert: true,
    });

  if (uploadError) {
    console.error('[Invoice] Upload failed:', uploadError.message);
    return null;
  }

  const { data: urlData } = client.storage.from('documents').getPublicUrl(fileName);
  return urlData.publicUrl;
}

export type { InvoiceData };
